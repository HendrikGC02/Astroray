#!/usr/bin/env python3
"""Download pkg71 benchmark scenes into the local gitignored cache.

The download/verification shape follows the Apache-2.0 Blender benchmark
project's manifest-driven scene cache pattern:
https://projects.blender.org/blender/blender-benchmark
"""

from __future__ import annotations

import argparse
import hashlib
import tomllib
import urllib.request
import zipfile
from pathlib import Path
from typing import Iterable


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "manifest.toml"
CACHE = ROOT / "cache"
ATTRIBUTION = CACHE / "ATTRIBUTION.md"

DISALLOWED_URL_MATCHES = (
    "victor",
    "cc-by-nc",
    "cc-by-nc-sentinel.invalid/victor",
)

assert DISALLOWED_URL_MATCHES, "CC-BY-NC disallowed URL list must never be empty"
assert any("sentinel" in item for item in DISALLOWED_URL_MATCHES), (
    "CC-BY-NC disallowed URL list must keep a sentinel test value"
)


def _load_manifest() -> list[dict]:
    with MANIFEST.open("rb") as fh:
        return tomllib.load(fh).get("scene", [])


def _assert_allowed_url(url: str) -> None:
    lowered = url.lower()
    for blocked in DISALLOWED_URL_MATCHES:
        assert blocked.lower() not in lowered, (
            f"Refusing to fetch disallowed CC-BY-NC scene URL: {url}"
        )


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _verify(path: Path, expected: str, allow_unpinned: bool) -> str:
    actual = _sha256(path)
    if expected and expected != "pending":
        if actual.lower() != expected.lower():
            raise RuntimeError(
                f"SHA-256 mismatch for {path.name}: expected {expected}, got {actual}"
            )
    elif not allow_unpinned:
        raise RuntimeError(
            f"{path.name} has no pinned SHA-256 in {MANIFEST}. "
            "Re-run with --allow-unpinned for first local audit, then pin the hash."
        )
    return actual


def _write_attribution(scenes: Iterable[dict]) -> None:
    cc_by = [s for s in scenes if str(s.get("license", "")).upper().startswith("CC-BY")]
    if not cc_by:
        return
    lines = [
        "# Benchmark Scene Attribution",
        "",
        "Generated by `fetch_scenes.py` for CC-BY scenes cached locally.",
        "",
    ]
    for scene in cc_by:
        lines.append(f"- {scene['attribution']}")
    ATTRIBUTION.write_text("\n".join(lines) + "\n", encoding="utf-8")


def fetch_scene(scene: dict, *, dry_run: bool, allow_unpinned: bool) -> tuple[str, str]:
    url = scene["url"]
    _assert_allowed_url(url)
    if "NC" in str(scene.get("license", "")).upper():
        raise RuntimeError(f"Refusing non-commercial scene license: {scene}")

    target = CACHE / scene["archive"]
    if dry_run:
        return scene["id"], f"would fetch {url} -> {target}"

    CACHE.mkdir(parents=True, exist_ok=True)
    if not target.exists():
        print(f"Downloading {scene['id']} from {url}")
        urllib.request.urlretrieve(url, target)
    actual = _verify(target, str(scene.get("sha256", "")), allow_unpinned)
    if target.suffix.lower() == ".zip":
        extract_dir = CACHE / scene["id"]
        if not extract_dir.exists():
            with zipfile.ZipFile(target) as zf:
                zf.extractall(extract_dir)
    return scene["id"], f"cached {target.name} sha256={actual}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--scene", action="append", help="Scene id to fetch; defaults to all")
    parser.add_argument("--dry-run", action="store_true", help="Validate manifest without downloading")
    parser.add_argument(
        "--allow-unpinned",
        action="store_true",
        help="Allow first-audit downloads whose manifest SHA-256 is still 'pending'",
    )
    args = parser.parse_args(argv)

    requested = set(args.scene or [])
    scenes = [s for s in _load_manifest() if not requested or s["id"] in requested]
    if requested and len(scenes) != len(requested):
        known = {s["id"] for s in _load_manifest()}
        missing = sorted(requested - known)
        raise SystemExit(f"Unknown scene id(s): {', '.join(missing)}")

    fetched = []
    for scene in scenes:
        scene_id, message = fetch_scene(scene, dry_run=args.dry_run, allow_unpinned=args.allow_unpinned)
        fetched.append(scene)
        print(f"{scene_id}: {message}")

    if not args.dry_run:
        _write_attribution(fetched)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
