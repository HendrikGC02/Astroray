def test_material_legacy_rgb_decode():
    """Material RGB fields are readable even when use_nodes is true (legacy
    cache fields persist)."""
    bf = BlendFile.from_path(FIXTURE)
    mat_blk = bf.by_code["MA"][0]
    mat_struct = bf.struct_of(mat_blk)
    # The legacy r/g/b fields exist; their concrete value is whatever Blender
    # writes for a node-driven material — we only assert decodability + range.
    r = bf.read_float(mat_blk, mat_struct, "r")[0]
    g = bf.read_float(mat_blk, mat_struct, "g")[0]
    b = bf.read_float(mat_blk, mat_struct, "b")[0]
    for c in (r, g, b):
        assert 0.0 <= c <= 1.0


def test_pointer_resolution():
    """FileGlobal.curscene → SC block round-trip."""
    bf = BlendFile.from_path(FIXTURE)
    glob = bf.by_code["GLOB"][0]
    fg = bf.sdna.struct_for("FileGlobal")
