"""pkg76 format-level tests — no bpy dependency.

Exercises the parser against the committed `synthetic_min.blend` fixture.
The fixture is regenerated by `tests/fixtures/build_synthetic_min.py` when
fields ever change; CI does not run that script.
"""

from __future__ import annotations

