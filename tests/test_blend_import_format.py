import pytest

from tools.blend_import.reader import BlendFile
from tools.blend_import.sdna import decode_header, FileHeader


FIXTURE = Path(__file__).parent / "fixtures" / "synthetic_min.blend"


pytestmark = pytest.mark.skipif(not FIXTURE.exists(),
                                reason="synthetic_min.blend fixture not committed")


def test_header_decode():
    raw = FIXTURE.read_bytes()
    h: FileHeader = decode_header(raw[:17])
    # Authored with Blender 5.1 (`compress=False`) — extended 17-byte header.
    assert h.header_size == 17
    assert h.pointer_size == 8
    assert h.little_endian is True
    assert h.version.startswith("05")  # Blender 5.x


def test_block_walk_finds_required_codes():
    bf = BlendFile.from_path(FIXTURE)
    # The fixture has exactly one of each parity-scope datablock.
    assert len(bf.by_code["SC"]) == 1, "expected 1 Scene block"
    assert len(bf.by_code["ME"]) == 1, "expected 1 Mesh block"
    assert len(bf.by_code["CA"]) == 1, "expected 1 Camera block"
    assert len(bf.by_code["LA"]) == 1, "expected 1 Lamp block"
    assert len(bf.by_code["MA"]) == 1, "expected 1 Material block"
    assert len(bf.by_code["WO"]) == 1, "expected 1 World block"
    assert len(bf.by_code["GLOB"]) == 1
    assert len(bf.by_code["DNA1"]) == 1
    assert len(bf.by_code["ENDB"]) == 1
    # Object count: camera + sun + cube.
    assert len(bf.by_code["OB"]) == 3


def test_sdna_struct_table():
    bf = BlendFile.from_path(FIXTURE)
